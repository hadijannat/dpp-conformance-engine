"""Published JSON Schemas, generated from the Pydantic models.

The models in ``dppce.models`` are the single source of truth. The files in ``v1/`` are
generated by ``scripts/gen_schemas.py``. A test fails if a file differs from the models.
See ADR 0003.
"""

from __future__ import annotations

import json
from pathlib import Path

from dppce.models import SCHEMA_MODELS

DIRECTORY = Path(__file__).parent / "v1"
_DIALECT = "https://json-schema.org/draft/2020-12/schema"


def generate() -> dict[str, str]:
    """Return ``{file name: file text}`` for every published contract."""
    files: dict[str, str] = {}
    for stem, model in sorted(SCHEMA_MODELS.items()):
        schema = {
            "$schema": _DIALECT,
            "$id": f"urn:dppce:schema:v1:{stem}",
            **model.model_json_schema(by_alias=True),
        }
        files[f"{stem}.schema.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    return files


def load(stem: str) -> dict[str, object]:
    """Load one published schema by its stem, for example ``ics``."""
    loaded: dict[str, object] = json.loads((DIRECTORY / f"{stem}.schema.json").read_text(encoding="utf-8"))
    return loaded
