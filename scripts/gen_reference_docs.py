"""Write the generated reference pages: command line, capability manifest, and schemas.

Usage: ``uv run python scripts/gen_reference_docs.py`` writes the pages.
``uv run python scripts/gen_reference_docs.py --check`` exits 1 if a page is stale.
"""

from __future__ import annotations

import argparse
import os
import sys
from itertools import combinations
from pathlib import Path

os.environ["COLUMNS"] = "100"  # argparse wraps help text to the terminal width

from dppce import __version__, schemas
from dppce.adapters.capabilities import manifest
from dppce.cli import _parser
from dppce.models import (
    SCHEMA_MODELS,
    AuthorityClass,
    ExecutionMode,
    ExecutionStatus,
    ReviewStatus,
    Tri,
    Verdict,
    VerdictRules,
)
from dppce.verdicts import claim_level, path_verdict, requirement_verdict, step_verdict

OUT = Path(__file__).resolve().parent.parent / "docs" / "reference"
NOTE = "This page is generated by `uv run just reference`. Do not edit it by hand.\n"


def _commands(parser: argparse.ArgumentParser, prefix: str) -> list[tuple[str, argparse.ArgumentParser]]:
    found: list[tuple[str, argparse.ArgumentParser]] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, sub in action.choices.items():
                full = f"{prefix} {name}"
                nested = _commands(sub, full)
                found.extend(nested or [(full, sub)])
    return found


def cli_page() -> str:
    parts = [
        "# Command-line reference\n",
        "Audience: operators and integrators.",
        "Purpose: list each command of `dppce`, its options, and its exit codes.",
        "Prerequisites: an installed engine.\n",
        NOTE,
        f"Engine version: `{__version__}`.\n",
        "## Exit codes\n",
        "| Code | Meaning |",
        "| --- | --- |",
        "| 0 | The command completed. For `run` and `replay`: the overall outcome is `pass`. |",
        "| 1 | The system under test failed: the overall outcome is `fail`. |",
        "| 2 | Usage or input error: bad arguments, an invalid file, or lint errors. |",
        "| 3 | Execution error: the overall outcome is `error`, or the engine failed. |",
        "| 4 | Report verification failed or is incomplete, or a replay digest differs. |",
        "| 5 | The run completed and the overall outcome is `inconclusive`. |\n",
        "Each command accepts `--json` and then writes one JSON document to standard output.\n",
        "## Commands\n",
    ]
    for name, sub in _commands(_parser(), "dppce"):
        parts += [f"### `{name}`\n", "```text", sub.format_help().rstrip(), "```\n"]
    parts += [
        "## Standalone verifier\n",
        "`python -m dppce.verifier ENVELOPE --trust BUNDLE --at TIME` verifies a report without the "
        "orchestrator and without the system under test. Exit codes: 0 complete, 4 failed or "
        "incomplete, 2 bad input.\n",
    ]
    return "\n".join(parts)


def capabilities_page() -> str:
    rows = [
        "# Capability manifest\n",
        "Audience: decision makers, vendors, and assessors.",
        "Purpose: show what this version can do, and what it cannot do.",
        "Prerequisites: none.\n",
        NOTE,
        f"Engine version: `{__version__}`. The command `dppce capabilities` prints the manifest of an "
        "installation, with the state of each optional dependency.\n",
        "A capability with the state `interface_only` is a deferred integration. It is not an "
        "implemented feature. A capability that is not `supported` or `experimental` never gives a pass.\n",
        "| Capability | Adapter | State | Needs | Description | Acceptance criteria for a state change |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for c in manifest().capabilities:
        needs = f"`{c.optional_dependency}`" if c.optional_dependency else ""
        rows.append(
            f"| `{c.id}` | {c.adapter} | {c.state.value} | {needs} | {c.description} "
            f"| {c.acceptance_criteria} |"
        )
    return "\n".join(rows) + "\n"


def schemas_page() -> str:
    rows = [
        "# Schema reference\n",
        "Audience: integrators and tool authors.",
        "Purpose: list the published data contracts and where their JSON Schemas are.",
        "Prerequisites: knowledge of JSON Schema.\n",
        NOTE,
        "The Pydantic models in `dppce.models` are the single source of truth. The JSON Schemas "
        "(draft 2020-12) in `src/dppce/schemas/v1/` are generated from them, and a test fails if "
        "they differ. Each document carries a `schema_version`. `dppce.migrations` upgrades an older "
        "document and rejects an unknown version.\n",
        "| Contract | Schema file | Identifier | Model | Purpose |",
        "| --- | --- | --- | --- | --- |",
    ]
    for stem, model in sorted(SCHEMA_MODELS.items()):
        schema = schemas.load(stem)
        purpose = " ".join(str(schema.get("description", "")).split()).split(". ")[0].rstrip(".")
        rows.append(
            f"| {stem} | `src/dppce/schemas/v1/{stem}.schema.json` | `{schema['$id']}` "
            f"| `{model.__name__}` | {purpose}. |"
        )
    return "\n".join(rows) + "\n"


def _subsets(items: list[Verdict]) -> list[tuple[Verdict, ...]]:
    return [c for size in range(len(items) + 1) for c in combinations(items, size)]


def _names(verdicts: tuple[Verdict, ...]) -> str:
    return ", ".join(v.value for v in verdicts) or "(none)"


def _step_rows() -> list[str]:
    rows = []
    for status in ExecutionStatus:
        if status is not ExecutionStatus.COMPLETED:
            verdict = step_verdict(status, None, False, VerdictRules())
            rows.append(f"| {status.value} | n/a | n/a | any | any | **{verdict.value}** |")
            continue
        passed = step_verdict(status, True, False, VerdictRules())
        rows.append(f"| completed | yes | n/a | any | any | **{passed.value}** |")
        for unreachable in (False, True):
            for on_failed in ("fail", "inconclusive"):
                for on_unreachable in ("inconclusive", "fail"):
                    rules = VerdictRules.model_validate(
                        {"on_check_failed": on_failed, "on_unreachable": on_unreachable}
                    )
                    verdict = step_verdict(status, False, unreachable, rules)
                    answer = "yes" if unreachable else "no"
                    rows.append(
                        f"| completed | no | {answer} | {on_failed} | {on_unreachable} | **{verdict.value}** |"
                    )
    return rows


def _requirement_rows() -> list[str]:
    draft, approved, reviewed = ReviewStatus.DRAFT, ReviewStatus.APPROVED, ExecutionMode.REVIEWED
    rows = []
    for applicability in (Tri.FALSE, Tri.UNKNOWN):
        verdict = requirement_verdict(applicability, False, [Verdict.PASS], reviewed, approved)[0]
        rows.append(f"| {applicability.value} | any | any | **{verdict.value}** | **{verdict.value}** |")
    conflict = requirement_verdict(Tri.TRUE, True, [Verdict.PASS], reviewed, approved)[0]
    rows.append(f"| true | yes | any | **{conflict.value}** | **{conflict.value}** |")
    for present in _subsets(list(Verdict)):
        normal = requirement_verdict(Tri.TRUE, False, list(present), reviewed, approved)[0]
        gated = requirement_verdict(Tri.TRUE, False, list(present), reviewed, draft)[0]
        rows.append(f"| true | no | {_names(present)} | **{normal.value}** | **{gated.value}** |")
    return rows


def verdicts_page() -> str:
    """The aggregation truth table, enumerated from the code. An independent test checks the code."""
    steps = [Verdict.PASS, Verdict.FAIL, Verdict.ERROR, Verdict.INCONCLUSIVE]
    path_rows = [
        f"| {a.value} | any | **{path_verdict(a, [Verdict.PASS]).value}** |" for a in (Tri.FALSE, Tri.UNKNOWN)
    ] + [f"| true | {_names(c)} | **{path_verdict(Tri.TRUE, list(c)).value}** |" for c in _subsets(steps)]
    claim_rows = [
        f"| {mode.value} | {label} | {status.value} | {claim_level(mode, authority, status).value} |"
        for mode in ExecutionMode
        for authority, label in (
            (AuthorityClass.ILLUSTRATIVE, "illustrative"),
            (AuthorityClass.LEGAL_OBLIGATION, "any other class"),
        )
        for status in ReviewStatus
    ]
    parts = [
        "# Verdict truth table\n",
        "Audience: assessors, and contributors who change a verdict rule.",
        "Purpose: publish every outcome of the verdict aggregation.",
        "Prerequisites: read the architecture contract, section 7.\n",
        NOTE,
        "The tables are enumerated from `dppce.verdicts`. The tests in "
        "`tests/core/test_verdict_truth_table.py` compare the same functions with an oracle that a "
        "different author wrote from the contract text. Order and repetition do not change a result, "
        "so each table lists the set of verdicts that is present.\n",
        "## 1. Step verdict\n",
        "| Execution status | Check passed | No answer from the system | Rule for a failed check "
        "| Rule for no answer | Step verdict |",
        "| --- | --- | --- | --- | --- | --- |",
        *_step_rows(),
        "\n## 2. Path verdict\n",
        "Every step of a path is required. A path with no step cannot pass.\n",
        "| Path applicability | Step verdicts present | Path verdict |",
        "| --- | --- | --- |",
        *path_rows,
        "\n## 3. Requirement verdict\n",
        "Paths are alternative ways to assess. The last column applies in reviewed mode when the "
        "interpretation is not approved.\n",
        "| Applicability | Declared as not implemented | Path verdicts present | Verdict "
        "| Verdict in reviewed mode, not approved |",
        "| --- | --- | --- | --- | --- |",
        *_requirement_rows(),
        "\n## 4. Claim level\n",
        "| Execution mode | Authority class | Review status | Claim level |",
        "| --- | --- | --- | --- |",
        *claim_rows,
        "\n## 5. Overall outcome\n",
        "The overall outcome uses the applicable mandatory requirements only. Precedence: no such "
        "requirement gives `inconclusive` (an empty run cannot pass); then `fail`; then `error`; then "
        "`inconclusive`; then `pass`. See the architecture contract, section 7.4.\n",
    ]
    return "\n".join(parts)


PAGES = {
    "verdict-truth-table.md": verdicts_page,
    "cli.md": cli_page,
    "capabilities.md": capabilities_page,
    "schemas.md": schemas_page,
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, build in PAGES.items():
        path, text = OUT / name, build()
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print(f"stale reference pages: {stale}; run `uv run just reference`", file=sys.stderr)
        return 1
    print(f"{len(PAGES)} reference pages; {'checked' if check else f'wrote {len(stale)}'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
