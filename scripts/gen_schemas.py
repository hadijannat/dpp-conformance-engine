"""Write the JSON Schemas that are generated from the Pydantic models.

Usage: ``uv run python scripts/gen_schemas.py`` writes the files.
``uv run python scripts/gen_schemas.py --check`` exits 1 if a file is missing or stale.
"""

from __future__ import annotations

import sys

from dppce.schemas import DIRECTORY, generate


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale: list[str] = []
    expected = generate()
    DIRECTORY.mkdir(parents=True, exist_ok=True)
    for name, text in expected.items():
        path = DIRECTORY / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8")
    extra = sorted(p.name for p in DIRECTORY.glob("*.schema.json") if p.name not in expected)
    if check and (stale or extra):
        print(f"stale: {stale}; not generated by a model: {extra}", file=sys.stderr)
        return 1
    print(f"{len(expected)} schemas; {'checked' if check else f'wrote {len(stale)}'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
