"""Write docs/reference/dependency-licenses.md from the installed environment.

Usage: ``uv run python scripts/gen_license_report.py``. The table is the output of pip-licenses.
Each dependency keeps its own license. This report relabels nothing.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "docs" / "reference" / "dependency-licenses.md"
HEAD = """# Dependency licenses

Audience: users, packagers, and assessors.
Purpose: list the license of each package in the locked development environment.
Prerequisites: none.

This page is generated by `uv run just licenses` with pip-licenses. Do not edit it by hand.
It lists the complete environment: run-time dependencies, optional extras, and development
tools. `uv.lock` pins the exact versions. Each package keeps its own license, and this
project does not relabel any of them. A license name here is the one that the package
declares in its metadata. It is not a legal review.

Run-time dependencies of the core: pydantic, pyyaml, jsonschema, referencing, rfc8785,
cryptography, joserfc, and asn1crypto. Optional extras: zxing-cpp and pillow (`qr`), and
aas-test-engines (`aas`).

"""


def main() -> int:
    command = [sys.executable, "-m", "piplicenses", "--format=markdown", "--with-urls", "--order=name"]
    done = subprocess.run(command, capture_output=True, text=True, check=False)  # noqa: S603 - fixed arguments
    if done.returncode != 0:
        print(done.stderr, file=sys.stderr)
        return done.returncode
    OUT.write_text(HEAD + done.stdout.strip() + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {max(done.stdout.count(chr(10)) - 2, 0)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
